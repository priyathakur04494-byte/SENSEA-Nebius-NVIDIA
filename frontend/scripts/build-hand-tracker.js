/*
 * Bundles handtracker/{template.html,classifier.js,page.js} into ONE string
 * module the app can drop into an iframe (web) or WebView (phones):
 *   src/generated/handTrackerHtml.ts
 *
 * Run after editing anything in handtracker/:   npm run build:tracker
 */
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "handtracker");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8");
// "</script" inside the JS would end the inline script early.
const safe = (s) => s.replace(/<\/script/gi, "<\\/script");
const html = read("template.html")
  .replace("/*__CLASSIFIER__*/", () => safe(read("classifier.js")))
  .replace("/*__PAGE__*/", () => safe(read("page.js")));
const out = path.join(__dirname, "..", "src", "generated", "handTrackerHtml.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  "// AUTO-GENERATED by scripts/build-hand-tracker.js — edit handtracker/*, not this file.\n" +
    "export const HAND_TRACKER_TEMPLATE: string = " + JSON.stringify(html) + ";\n"
);
console.log("wrote", path.relative(process.cwd(), out), (html.length / 1024).toFixed(1) + " KB");
